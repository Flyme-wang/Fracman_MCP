"""Macro validation, wrapping and template tests."""

from __future__ import annotations

import pytest

from fracman_mcp.macro import (
    DFN_TEMPLATE,
    MacroValidationError,
    dfn_template,
    list_commands,
    normalize,
    read_macro,
    strip_comments,
    validate,
    wrap_batch,
    wrap_live,
)


def test_normalize_crlf_and_bom():
    assert normalize("\ufeffBEGIN SetSeed\r\nEND") == "BEGIN SetSeed\nEND\n"


def test_strip_comments_keeps_hash_inside_quotes():
    code = 'A = "#notacomment"\n# real comment\nB = 1'
    assert strip_comments(code) == 'A = "#notacomment"\n\nB = 1'


def test_validate_rejects_logtofile_line_and_begin():
    with pytest.raises(MacroValidationError):
        validate("LOGTOFILE\n", live=False)
    with pytest.raises(MacroValidationError):
        validate("BEGIN LOGTOFILE\nFILE = \"x.fml\"\nEND\n", live=False)
    # Inside a comment it is harmless.
    validate("# BEGIN LOGTOFILE\nBEGIN SetSeed\nSeed = 1\nEND\n", live=False)


def test_validate_live_exit_gate():
    with pytest.raises(MacroValidationError):
        validate("EXIT\n", live=True)
    validate("EXIT\n", live=True, allow_exit=True)
    warnings = validate("EXIT\n", live=False)
    assert any("EXIT" in item for item in warnings)


def test_validate_rejects_exitonerror_for_live_only():
    code = "BEGIN EXITONERROR\nEND\n"
    with pytest.raises(MacroValidationError):
        validate(code, live=True)
    validate(code, live=False)


def test_validate_deleteall_gate_and_warnings():
    with pytest.raises(MacroValidationError):
        validate("DeleteAll\n", live=True)
    validate("DeleteAll\n", live=True, allow_destructive=True)
    warnings = validate(
        "BEGIN_LOOP\nRunMacro\nBEGIN SetSeed\nSeed = 1\nEND\n",
        live=False,
    )
    assert any("BEGIN_LOOP" in item for item in warnings)
    assert any("RunMacro" in item for item in warnings)


def test_wrap_live_and_batch():
    live = wrap_live("BEGIN SetSeed\nSeed = 1\nEND\n", "C:/tmp/live.fml")
    assert live.startswith("# Generated by fracman-mcp (live session)")
    assert "BEGIN LOGTOFILE" in live
    assert 'FILE = "C:/tmp/live.fml"' in live
    assert "EXITONERROR" not in live

    batch = wrap_batch("BEGIN SetSeed\nSeed = 1\nEND\n", "C:/tmp/run.fml")
    assert "BEGIN EXITONERROR" in batch
    assert batch.rstrip().endswith("EXIT")
    assert batch.count("\nEXIT\n") == 1  # exactly one bare EXIT line
    # An explicit EXIT is not duplicated.
    explicit = wrap_batch("EXIT\n", "C:/tmp/run.fml")
    assert explicit.rstrip().endswith("EXIT")
    assert explicit.count("\nEXIT\n") == 1


def test_read_macro_encodings(tmp_path):
    gb = tmp_path / "gb.fmf"
    gb.write_bytes("# 中文注释\nBEGIN SetSeed\nSeed = 1\nEND\n".encode("gb18030"))
    text = read_macro(gb)
    assert "中文注释" in text
    assert "BEGIN SetSeed" in text


def test_read_macro_rejects_missing_and_oversize(tmp_path):
    with pytest.raises(MacroValidationError):
        read_macro(tmp_path / "missing.fmf")
    big = tmp_path / "big.fmf"
    big.write_bytes(b"x" * (4 * 1024 * 1024 + 1))
    with pytest.raises(MacroValidationError):
        read_macro(big)


def test_dfn_template_has_no_placeholders():
    text = dfn_template(seed=7, count=12, export_path="C:/tmp/out.fab")
    assert "__" not in text
    assert "Seed = 7" in text
    assert "Count = 12" in text
    assert '"C:/tmp/out.fab"' in text
    validate(text, live=False)
    commands = list_commands(text)
    assert commands[0] == "SetSeed"
    assert "GenerateFractureSet" in commands
    # The shipped template and the builder must stay in sync.
    for marker in ("__SEED__", "__COUNT__", "__EXPORT__"):
        assert marker in DFN_TEMPLATE
